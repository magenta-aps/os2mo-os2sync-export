async def get_pending_org_unit_events(
    graphql_client: GraphQLClient, subject: str
) -> list[dict]:
    response = await graphql_client.execute(
        query=gql("""
            query PendingOrgUnitEvents($subject: [String!]) {
              events(filter: {subjects: $subject}) {
                objects {
                  subject
                }
              }
            }
        """),
        variables={"subject": [subject]},
    )
    data = graphql_client.get_data(response)
    return data["events"]["objects"]


@pytest.mark.integration_test
async def test_unit_not_found(
    graphql_client: GraphQLClient,
    set_settings,
) -> None:
    # Arrange
    os2sync_mock = AsyncMock()
    uuid = uuid4()

    # Act
    result = await sync_orgunit(
        settings=set_settings(),
        graphql_client=graphql_client,
        os2sync_client=os2sync_mock,
        uuid=uuid,
    )

    # Assert
    # A unit MO has never known about is treated the same as a deleted one:
    # it must be removed from fk-org rather than left dangling there.
    assert result is None
    os2sync_mock.delete_orgunit.assert_awaited_once_with(uuid)
    os2sync_mock.update_org_unit.assert_not_called()


